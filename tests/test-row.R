library(ROW)
data(ncds)
f <- ~ white + maemp + factor(scht) + qmab + qmab2 + qvab + qvab2 + paed_u + maed_u + agepa + agema + sib_u
fit <- row_ate(ncds, "Dmult", "wage", f, reference = "None")
stopifnot(inherits(fit, "row"), fit$lambda_K2 == 8, nrow(fit$estimates) == 2)
stopifnot(abs(coef(fit)[["O/eq vs None"]] - 0.113) < 0.002, abs(coef(fit)[[">=A/eq vs None"]] - 0.279) < 0.002)
stopifnot(all(fit$estimates$se > 0.02 & fit$estimates$se < 0.03))
# lambda = Inf reproduces AIPW; fixed lambda works
a <- row_ate(ncds, "Dmult", "wage", f, reference = "None", lambda = Inf)
stopifnot(abs(coef(a)[["O/eq vs None"]] - 0.111) < 0.002)
# simulated three-arm data with known ATE (2 and 3)
set.seed(1); n <- 3000; x <- rnorm(n); z <- rbinom(n, 1, 0.5)
lp <- cbind(0, 0.8 * x - 0.3, -0.6 * x + 0.5 * z); p <- exp(lp) / rowSums(exp(lp))
A <- apply(p, 1, function(q) sample(1:3, 1, prob = q))
y <- 1 + x + 0.5 * z + c(0, 2, 3)[A] + rnorm(n)
s <- row_ate(data.frame(A, y, x, z), "A", "y", ~ x + z)
stopifnot(all(abs(coef(s) - c(2, 3)) < 4 * s$estimates$se))
p2 <- row_path(data.frame(A, y, x, z), "A", "y", ~ x + z, grid = c(1, Inf))
stopifnot(nrow(p2) == 4)
cat("all tests passed\n")
